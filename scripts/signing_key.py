"""
PlatformIO pre-build script: compiles the OTA signing public key into the firmware.

Generates `netignite_signing_key.h` in the build directory. If the environment's
`custom_signing_key` (a PEM ECDSA P-256 public key, see scripts/generate_signing_key.sh) exists,
the header defines NETIGNITE_OTA_PUBLIC_KEY and the firmware then only installs OTA updates with a
valid signature. Without the file, updates are checked by SHA-256 only.

The emulator environment uses a test key whose private half is in the repository
(test/emulator/keys); it is refused for any other environment.
"""

import os

Import("env")  # noqa: F821 - provided by PlatformIO (SCons)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
key_option = env.GetProjectOption("custom_signing_key", "").strip()  # noqa: F821
key_path = os.path.join(project_dir, key_option) if key_option else ""
build_flags = env.GetProjectOption("build_flags", [])  # noqa: F821
if isinstance(build_flags, str):
    build_flags = [build_flags]
is_emulator = any("NETIGNITE_EMULATOR" in flag for flag in build_flags)

out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
header = os.path.join(out_dir, "netignite_signing_key.h")

lines = [
    "#pragma once",
    "// Generated by scripts/signing_key.py. Do not edit.",
]

if key_path and os.path.isfile(key_path):
    if "test" in os.path.relpath(key_path, project_dir).replace("\\", "/").split("/") and not is_emulator:
        raise SystemExit(f"Refusing to build {env.subst('$PIOENV')} with the test signing key {key_option}")  # noqa: F821
    with open(key_path, "r", encoding="ascii") as handle:
        pem = handle.read().strip() + "\n"
    if "BEGIN PUBLIC KEY" not in pem:
        raise SystemExit(f"{key_option} isn't a PEM public key")
    escaped = pem.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    lines.append(f'#define NETIGNITE_OTA_PUBLIC_KEY "{escaped}"')
    print(f"OTA updates must be signed with the key for {key_option}")
else:
    if key_option:
        print(f"No {key_option}: OTA updates are checked by SHA-256 only (no signature)")

new_content = "\n".join(lines) + "\n"
old_content = open(header, encoding="ascii").read() if os.path.exists(header) else None
if new_content != old_content:
    with open(header, "w", encoding="ascii", newline="\n") as handle:
        handle.write(new_content)

env.Append(CPPPATH=[out_dir])  # noqa: F821
